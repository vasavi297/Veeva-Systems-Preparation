/*1.From the above tables write a sql query to find all the orders issued by salesman paul adam*/
Select *
from orders_jocata o 
join salesman_jocata s
on o.salesman_id=s.salesman_id
where s.name='Paul Adam';

/*2.Write SQL Query to find all the orders generated by London based sales people*/
Select *
from orders_jocata o 
join salesman_jocata s
on o.salesman_id=s.salesman_id
where s.city='London';

/*3.Write an SQL Query to find all the orders generated by sales people who works for customer id 3007*/
