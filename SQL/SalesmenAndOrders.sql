from orders_jocata o 
join salesman_jocata s
on o.salesman_id=s.salesman_id
where o.customer_id=3007;

/*4.Display all the orders exceeding average value on 10th October 2012*/
select * from orders_jocata
where purch_amt>
(select avg(purch_amt) 
from orders_jocata
where ord_date='2012-10-10');

